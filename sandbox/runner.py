#!/usr/bin/env python3
"""Quarantine in-sandbox runner.

Runs INSIDE the disposable detonation container. It is the only code that
executes next to the untrusted package, so it is stdlib-only and assumes it
can be lied to: everything it reports is treated as *best-effort telemetry*.
Verdict-critical signals (egress, OOM, pid exhaustion, exit codes) are
collected outside the sandbox by the control plane and the egress proxy.

Phases:  plant decoys -> install (lifecycle scripts run) -> exercise harness
         -> MCP probe (optional) -> summary

Every event is one JSON line on stdout prefixed with {"q":1,...}.

Privilege split: the runner is uid 0 inside the sandbox with ONLY the SETUID,
SETGID, KILL and DAC_READ_SEARCH capabilities (all others dropped by Docker,
no-new-privileges set). Every piece of package code runs as uid 10001 with an
empty capability set. Different uid => the package cannot signal the runner,
open /proc/<runner>/fd/1 to forge telemetry, or read the job file; it can only
write to the pipes the runner gives it, and those are parsed as plain output.
"""
import ctypes
import ctypes.util
import json
import resource
import os
import signal
import struct
import subprocess
import sys
import threading
import time

DEV_UID = DEV_GID = 10001
JOB_PATH = os.environ.get("Q_JOB", "/job/job.json")
HOME = os.environ.get("HOME", "/home/dev")
WORK = "/work"
MAX_LINES_PER_PHASE = 300
MAX_LINE_LEN = 400
MAX_PROC_EVENTS = 150

_print_lock = threading.Lock()
_t0 = time.time()


def emit(kind, **fields):
    fields.update({"q": 1, "type": kind, "t": round(time.time() - _t0, 3)})
    line = json.dumps(fields, default=str)
    with _print_lock:
        sys.stdout.write(line + "\n")
        sys.stdout.flush()


# --------------------------------------------------------------------------
# Decoy credentials (honeytokens). Values are random per run, generated by the
# control plane; they are worthless outside this sandbox.
# --------------------------------------------------------------------------
def plant_decoys(tokens):
    files = {
        f"{HOME}/.npmrc": f"//registry.npmjs.org/:_authToken={tokens['npm']}\n",
        f"{HOME}/.aws/credentials": (
            "[default]\n"
            f"aws_access_key_id = {tokens['aws_id']}\n"
            f"aws_secret_access_key = {tokens['aws_secret']}\n"
        ),
        f"{HOME}/.ssh/id_rsa": (
            "-----BEGIN OPENSSH PRIVATE KEY-----\n"
            f"{tokens['ssh']}\n"
            "-----END OPENSSH PRIVATE KEY-----\n"
        ),
        f"{HOME}/.config/gh/hosts.yml": (
            f"github.com:\n    oauth_token: {tokens['github']}\n    user: dev\n"
        ),
        # A sibling project's secrets, NOT the harness cwd: dotenv-style libraries
        # legitimately read ./.env, so a decoy there would flag honest packages.
        f"{HOME}/projects/payments-api/.env": (
            f"OPENAI_API_KEY={tokens['openai']}\nDATABASE_URL=postgres://app:{tokens['db']}@db:5432/prod\n"),
    }
    pid = os.fork()
    if pid == 0:  # child: become the dev user, write the files, exit
        try:
            drop_privileges()
            for path, content in files.items():
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as fh:
                    fh.write(content)
                os.chmod(path, 0o600)
            with open("/tmp/npmrc-empty", "w") as fh:  # npm itself never reads the decoy ~/.npmrc
                fh.write("")
            os.makedirs(WORK, exist_ok=True)
            with open(f"{WORK}/package.json", "w") as fh:  # a host project for `npm install`
                json.dump({"name": "quarantine-host-project", "version": "1.0.0", "private": True}, fh)
            os._exit(0)
        except BaseException:
            os._exit(1)
    _, status = os.waitpid(pid, 0)
    emit("decoys_planted", files=sorted(files.keys()), ok=status == 0)
    return list(files.keys())


def drop_privileges():
    """Irrevocably become uid/gid 10001 with no supplementary groups and no capabilities."""
    if os.getuid() == 0:
        os.setgroups([])
        os.setgid(DEV_GID)
        os.setuid(DEV_UID)


# --------------------------------------------------------------------------
# inotify watcher for decoy file opens (ctypes, no deps)
# --------------------------------------------------------------------------
IN_ACCESS = 0x00000001
IN_OPEN = 0x00000020


def watch_decoys(paths, stop):
    libc_name = ctypes.util.find_library("c") or "libc.so.6"
    try:
        libc = ctypes.CDLL(libc_name, use_errno=True)
        fd = libc.inotify_init1(os.O_NONBLOCK)
        if fd < 0:
            raise OSError(ctypes.get_errno(), "inotify_init1")
    except Exception as exc:  # gVisor or seccomp may refuse; degrade, don't die
        emit("monitor_warning", what="inotify unavailable", error=str(exc))
        return
    wd_map = {}
    for p in paths:
        wd = libc.inotify_add_watch(fd, p.encode(), IN_OPEN | IN_ACCESS)
        if wd >= 0:
            wd_map[wd] = p
    seen = set()
    while not stop.is_set():
        try:
            buf = os.read(fd, 4096)
        except BlockingIOError:
            time.sleep(0.05)
            continue
        except OSError:
            time.sleep(0.05)
            continue
        i = 0
        while i + 16 <= len(buf):
            wd, mask, _cookie, length = struct.unpack_from("iIII", buf, i)
            i += 16 + length
            path = wd_map.get(wd)
            if path and path not in seen:
                seen.add(path)
                emit("decoy_read", path=path, phase=CURRENT_PHASE[0])


# --------------------------------------------------------------------------
# /proc sampler: new processes, peak pid count, outbound connection attempts
# --------------------------------------------------------------------------
TCP_STATES = {"01": "ESTABLISHED", "02": "SYN_SENT"}


def _uid_of(pid):
    try:
        with open(f"/proc/{pid}/status") as fh:
            for line in fh:
                if line.startswith("Uid:"):
                    return int(line.split()[1])
    except (OSError, ValueError, IndexError):
        pass
    return None


def kill_package_processes(rounds=6):
    """Kill EVERY process running as the package uid, whatever session or process group
    it moved itself into (setsid/daemonize can't escape this). Returns processes killed."""
    killed = 0
    for _ in range(rounds):
        found = 0
        for p in os.listdir("/proc"):
            if p.isdigit() and _uid_of(int(p)) == DEV_UID:
                found += 1
                try:
                    os.kill(int(p), signal.SIGKILL)
                    killed += 1
                except OSError:
                    pass
        if not found:
            break
        time.sleep(0.1)
    return killed


def _hex_to_addr(h):
    ip_hex, port_hex = h.split(":")
    port = int(port_hex, 16)
    if len(ip_hex) == 8:
        ip = ".".join(str(b) for b in bytes.fromhex(ip_hex)[::-1])
    else:
        raw = bytes.fromhex(ip_hex)
        words = [raw[i:i + 4][::-1] for i in range(0, 16, 4)]
        ip = ":".join(b.hex() for b in words)
    return f"{ip}:{port}"


LIMITS = {"nproc": 0, "mem_mb": 0}  # set from the job: the package's process and memory budget
GUARD = {"processes": False, "memory": False, "phase": None}


def _limit_nproc():
    """Runs in the child before exec. RLIMIT_NPROC counts threads too (node alone has ~10), so
    the kernel limit is a backstop at twice the budget; the guard trips first, on processes."""
    if LIMITS["nproc"]:
        lim = LIMITS["nproc"] * 2
        resource.setrlimit(resource.RLIMIT_NPROC, (lim, lim))


def _rss_mb(pid):
    try:
        with open(f"/proc/{pid}/statm") as fh:
            return int(fh.read().split()[1]) * resource.getpagesize() / 1048576
    except (OSError, ValueError, IndexError):
        return 0.0


def resource_guard(pids, stats):
    """Enforce the package's budgets from inside the sandbox, whatever the runtime.

    Under gVisor the container's pids/memory cgroups also bound the sandbox kernel itself,
    so a fork bomb or memory balloon can take the whole sandbox down before anything is
    reported. Catching it here (90% of the process budget, 80% of memory) keeps the evidence."""
    dev = [p for p in pids if _uid_of(p) == DEV_UID]
    stats["dev_pids_peak"] = max(stats.get("dev_pids_peak", 0), len(dev))
    if not dev:
        return
    if GUARD.get("phase") == CURRENT_PHASE[0]:  # already tripped this phase: keep it down
        kill_package_processes(rounds=3)
        return
    cap, mem_cap = LIMITS["nproc"], LIMITS["mem_mb"]
    hits = []
    if cap and not GUARD["processes"] and len(dev) >= int(cap * 0.9):
        hits.append(dict(resource="processes", count=len(dev), cap=cap))
    if mem_cap and not GUARD["memory"]:
        rss = sum(_rss_mb(p) for p in dev)
        stats["dev_rss_peak_mb"] = max(stats.get("dev_rss_peak_mb", 0), round(rss))
        if rss >= mem_cap * 0.8:
            hits.append(dict(resource="memory", rss_mb=round(rss), cap_mb=mem_cap))
    for h in hits:
        GUARD[h["resource"]] = True
        emit("resource_exhausted", phase=CURRENT_PHASE[0], **h)
    if hits:
        GUARD["phase"] = CURRENT_PHASE[0]
        kill_package_processes(rounds=20)


def sample_proc(stop, self_pids, stats):
    seen_pids = set()
    seen_conns = set()
    proc_events = 0
    suppressed = 0
    while not stop.is_set():
        try:
            pids = [int(p) for p in os.listdir("/proc") if p.isdigit()]
        except OSError:
            pids = []
        stats["pids_peak"] = max(stats["pids_peak"], len(pids))
        resource_guard(pids, stats)
        for pid in pids:
            if pid in seen_pids or pid in self_pids:
                continue
            seen_pids.add(pid)
            try:
                with open(f"/proc/{pid}/cmdline", "rb") as fh:
                    cmd = fh.read().replace(b"\0", b" ").decode(errors="replace").strip()
            except OSError:
                continue
            # Only package code (uid 10001) is reported. Filtering by uid, not by name,
            # means a package cannot hide a process by putting "runner.py" in its argv.
            if not cmd or CURRENT_PHASE[0] == "init" or _uid_of(pid) != DEV_UID:
                continue
            stats["procs_total"] += 1
            if proc_events < MAX_PROC_EVENTS:
                proc_events += 1
                emit("proc", pid=pid, cmd=cmd[:MAX_LINE_LEN], phase=CURRENT_PHASE[0])
            else:
                suppressed += 1
        for table in ("/proc/net/tcp", "/proc/net/tcp6"):
            try:
                with open(table) as fh:
                    rows = fh.read().splitlines()[1:]
            except OSError:
                continue
            for row in rows:
                cols = row.split()
                if len(cols) < 4 or cols[3] not in TCP_STATES:
                    continue
                remote = _hex_to_addr(cols[2])
                if remote.startswith("0.0.0.0") or remote in seen_conns:
                    continue
                seen_conns.add(remote)
                if len(seen_conns) > 100:
                    continue  # bounded: a scan of the address space is already evident
                emit("net_attempt", dst=remote, state=TCP_STATES[cols[3]], phase=CURRENT_PHASE[0])
        time.sleep(0.1)
    stats["proc_events_suppressed"] = suppressed


# --------------------------------------------------------------------------
# Filesystem snapshot: persistence attempts (shell profiles, dropped files)
# --------------------------------------------------------------------------
SKIP_DIRS = {".npm", "node_modules", "pylib", "__pycache__", ".cache/pip"}


def fs_snapshot(roots=(HOME, WORK)):
    snap = {}
    for root in roots:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
            for fn in filenames:
                p = os.path.join(dirpath, fn)
                try:
                    st = os.lstat(p)
                except OSError:
                    continue
                snap[p] = (st.st_size, st.st_mtime_ns)
            if len(snap) > 5000:
                return snap
    return snap


def fs_diff(before, after, phase):
    changes = 0
    for p, meta in after.items():
        if p.endswith("package-lock.json") or p.endswith("/work/package.json"):
            continue
        if p not in before:
            kind = "created"
        elif before[p] != meta:
            kind = "modified"
        else:
            continue
        changes += 1
        if changes <= 40:
            emit("fs_change", path=p, change=kind, size=meta[0], phase=phase)
    return changes


# --------------------------------------------------------------------------
# Phase execution
# --------------------------------------------------------------------------
CURRENT_PHASE = ["init"]


def run_phase(name, argv, timeout, cwd=WORK, env=None, stdin_data=None):
    before = fs_snapshot()
    res = _run_phase(name, argv, timeout, cwd, env, stdin_data)
    fs_diff(before, fs_snapshot(), name)
    return res


def _run_phase(name, argv, timeout, cwd=WORK, env=None, stdin_data=None):
    CURRENT_PHASE[0] = name
    emit("phase_start", phase=name, argv=argv, timeout=timeout)
    t = time.time()
    try:
        proc = subprocess.Popen(
            argv, cwd=cwd, env=env, stdin=subprocess.PIPE if stdin_data else subprocess.DEVNULL,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, start_new_session=True,
            user=DEV_UID, group=DEV_GID, extra_groups=[], umask=0o022, preexec_fn=_limit_nproc,
        )
    except OSError as exc:
        emit("phase_end", phase=name, exit_code=None, error=str(exc), seconds=0)
        return {"exit_code": None, "error": str(exc), "output": ""}
    if stdin_data:
        try:
            proc.stdin.write(stdin_data)
            proc.stdin.close()
        except OSError:
            pass
    lines = []
    count = [0]

    def pump():
        for raw in iter(proc.stdout.readline, b""):
            count[0] += 1
            text = raw.decode(errors="replace").rstrip("\n")[:MAX_LINE_LEN]
            if len(lines) < 2000:
                lines.append(text)
            if count[0] <= MAX_LINES_PER_PHASE:
                emit("output", phase=name, line=text)

    th = threading.Thread(target=pump, daemon=True)
    th.start()
    timed_out = False
    try:
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        kill_package_processes(rounds=12)  # forking trees need repeated sweeps
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass
    th.join(timeout=2)
    # Lifecycle discipline inside the box too: nothing a phase started may linger
    # into the next phase (e.g. a daemon spawned by a postinstall script).
    lingering = kill_package_processes()
    if lingering:
        emit("lingering_killed", phase=name, processes=lingering)
    res = {
        "exit_code": proc.returncode,
        "timed_out": timed_out,
        "seconds": round(time.time() - t, 2),
        "lines": count[0],
        "output": "\n".join(lines[-80:]),
    }
    emit("phase_end", phase=name, exit_code=proc.returncode, timed_out=timed_out,
         seconds=res["seconds"], lines=count[0])
    return res


# --------------------------------------------------------------------------
# MCP stdio probe: initialize -> tools/list -> call each tool with canary args
# --------------------------------------------------------------------------
def _dummy_for(schema):
    t = (schema or {}).get("type")
    if t == "string":
        return "quarantine-probe"
    if t in ("number", "integer"):
        return 1
    if t == "boolean":
        return False
    if t == "array":
        return []
    if t == "object":
        return {k: _dummy_for(v) for k, v in (schema.get("properties") or {}).items()}
    return "quarantine-probe"


def mcp_probe(command, env, timeout):
    before = fs_snapshot()
    res = _mcp_probe(command, env, timeout)
    fs_diff(before, fs_snapshot(), "mcp")
    return res


def _mcp_probe(command, env, timeout):
    CURRENT_PHASE[0] = "mcp"
    emit("phase_start", phase="mcp", argv=command, timeout=timeout)
    t0 = time.time()
    try:
        proc = subprocess.Popen(command, cwd=WORK, env=env, stdin=subprocess.PIPE,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                start_new_session=True, user=DEV_UID, group=DEV_GID, extra_groups=[],
                                umask=0o022)
    except OSError as exc:
        emit("phase_end", phase="mcp", exit_code=None, error=str(exc), seconds=0)
        return {"error": str(exc)}

    responses = {}
    resp_lock = threading.Condition()

    def reader():
        for raw in iter(proc.stdout.readline, b""):
            try:
                msg = json.loads(raw)
            except ValueError:
                emit("output", phase="mcp", line=raw.decode(errors="replace")[:MAX_LINE_LEN])
                continue
            if isinstance(msg, dict) and "id" in msg:
                with resp_lock:
                    responses[msg["id"]] = msg
                    resp_lock.notify_all()

    def err_reader():
        for raw in iter(proc.stderr.readline, b""):
            emit("output", phase="mcp", line=raw.decode(errors="replace").rstrip()[:MAX_LINE_LEN])

    threading.Thread(target=reader, daemon=True).start()
    threading.Thread(target=err_reader, daemon=True).start()

    def call(i, method, params, wait=8.0):
        msg = {"jsonrpc": "2.0", "id": i, "method": method, "params": params}
        try:
            proc.stdin.write((json.dumps(msg) + "\n").encode())
            proc.stdin.flush()
        except OSError:
            return None
        deadline = time.time() + wait
        with resp_lock:
            while i not in responses and time.time() < deadline:
                resp_lock.wait(timeout=0.2)
            return responses.get(i)

    result = {"tools": [], "calls": []}
    init = call(1, "initialize", {"protocolVersion": "2025-06-18", "capabilities": {},
                                  "clientInfo": {"name": "quarantine-probe", "version": "1.0"}})
    if init:
        result["server"] = (init.get("result") or {}).get("serverInfo")
        try:
            proc.stdin.write((json.dumps({"jsonrpc": "2.0", "method": "notifications/initialized"}) + "\n").encode())
            proc.stdin.flush()
        except OSError:
            pass
        listed = call(2, "tools/list", {})
        tools = ((listed or {}).get("result") or {}).get("tools") or []
        for tool in tools[:10]:
            entry = {"name": tool.get("name"), "description": (tool.get("description") or "")[:2000],
                     "inputSchema": tool.get("inputSchema")}
            result["tools"].append(entry)
            emit("mcp_tool", name=entry["name"], description=entry["description"])
        for n, tool in enumerate(tools[:5]):
            if time.time() - t0 > timeout - 3:
                break
            args = _dummy_for(tool.get("inputSchema") or {"type": "object"})
            resp = call(10 + n, "tools/call", {"name": tool.get("name"), "arguments": args})
            text = json.dumps((resp or {}).get("result") or (resp or {}).get("error") or "no response")[:600]
            result["calls"].append({"name": tool.get("name"), "args": args, "response": text})
            emit("mcp_call", name=tool.get("name"), args=args, response=text)
            time.sleep(0.5)  # give side effects a moment to show up in telemetry
    else:
        emit("monitor_warning", what="MCP server did not answer initialize")
    kill_package_processes()
    emit("phase_end", phase="mcp", exit_code=proc.poll(), seconds=round(time.time() - t0, 2))
    return result


# --------------------------------------------------------------------------
def main():
    with open(JOB_PATH) as fh:
        job = json.load(fh)
    emit("runner_start", run_id=job.get("run_id"), uid=os.getuid(), package_uid=DEV_UID,
         hostname=os.uname().nodename,
         secret_env=[k for k in os.environ if "VULTR" in k or k.endswith("_API_KEY")])
    decoy_paths = plant_decoys(job["decoys"])
    LIMITS.update({k: int(v) for k, v in (job.get("limits") or {}).items() if k in LIMITS})

    stop = threading.Event()
    stats = {"pids_peak": 0, "procs_total": 0}
    threading.Thread(target=watch_decoys, args=(decoy_paths, stop), daemon=True).start()
    threading.Thread(target=sample_proc, args=(stop, {os.getpid(), 1}, stats), daemon=True).start()
    time.sleep(0.2)

    proxy = job.get("proxy_url", "")
    base_env = {
        "HOME": HOME, "USER": "dev", "PATH": "/usr/local/bin:/usr/bin:/bin",
        "LANG": "C.UTF-8",
        "HTTP_PROXY": proxy, "HTTPS_PROXY": proxy, "http_proxy": proxy, "https_proxy": proxy,
        "NO_PROXY": "", "no_proxy": "",
        # Decoy credentials in env too: real malware (Shai-Hulud, s1ngularity) harvests both.
        "GITHUB_TOKEN": job["decoys"]["github"], "NPM_TOKEN": job["decoys"]["npm"],
        "AWS_ACCESS_KEY_ID": job["decoys"]["aws_id"], "AWS_SECRET_ACCESS_KEY": job["decoys"]["aws_secret"],
    }
    results = {}
    eco = job["ecosystem"]
    t = job.get("timeouts", {})
    if eco == "npm":
        env = dict(base_env, NPM_CONFIG_USERCONFIG="/tmp/npmrc-empty", npm_config_cache=f"{HOME}/.npm",
                   NODE_PATH=f"{WORK}/node_modules",
                   npm_config_update_notifier="false", npm_config_proxy=proxy, npm_config_https_proxy=proxy)
        results["install"] = run_phase(
            "install", ["npm", "install", "--no-audit", "--no-fund", "--foreground-scripts",
                        "--loglevel=http", job["package_file"]], t.get("install", 90), env=env)
    elif eco == "pypi":
        env = dict(base_env, PIP_DISABLE_PIP_VERSION_CHECK="1", PYTHONDONTWRITEBYTECODE="1")
        results["install"] = run_phase(
            "install", ["python3", "-m", "pip", "install", "--no-cache-dir", "--break-system-packages",
                        "--target", f"{WORK}/pylib", "--proxy", proxy, job["package_file"]],
            t.get("install", 120), env=env)
        env["PYTHONPATH"] = f"{WORK}/pylib"
    else:
        emit("monitor_warning", what=f"unknown ecosystem {eco}")
        env = base_env

    harness = job.get("harness")
    if harness:
        argv = ["node", harness["file"]] if harness["lang"] == "node" else ["python3", harness["file"]]
        results["exercise"] = run_phase("exercise", argv, t.get("exercise", 30), env=env)

    if job.get("mcp_command"):
        results["mcp"] = mcp_probe(job["mcp_command"], env, t.get("mcp", 25))

    time.sleep(0.6)  # let samplers catch trailing activity
    stop.set()
    time.sleep(0.15)
    CURRENT_PHASE[0] = "summary"
    emit("runner_done", stats=stats, results={k: {kk: vv for kk, vv in v.items() if kk != "output"}
                                              if isinstance(v, dict) else v for k, v in results.items()},
         outputs={k: v.get("output", "")[-3000:] for k, v in results.items() if isinstance(v, dict)})


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # never crash silently
        emit("runner_error", error=repr(exc))
        raise
